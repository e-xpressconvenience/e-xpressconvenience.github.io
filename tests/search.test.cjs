const assert=require('node:assert/strict');
const s=require('../assets/search-engine.js');
const now=Date.parse('2026-11-13T12:00:00Z');
const offer={productId:'phone',variantKey:'13-128-new',sellerId:'test-only',sellerVerified:true,stockStatus:'in_stock',currency:'LSL',sourceUrl:'https://example.test/offer',supplierCostMinor:10000,checkedAt:'2026-11-13T11:00:00Z',expiresAt:'2026-11-13T13:00:00Z'};
const policy={handlingMinor:200,fixedMarkupMinor:150,markupBps:500,paymentFeeBps:300};
assert.equal(s.quote(offer,policy,now).priceMinor,11186);
for(const invalid of [{sellerVerified:false},{stockStatus:'unknown'},{supplierCostMinor:NaN},{supplierCostMinor:-1},{currency:'ZAR'},{expiresAt:'2026-11-13T11:59:59Z'},{checkedAt:'2026-11-14T00:00:00Z'},{variantKey:''}])assert.equal(s.quote({...offer,...invalid},policy,now),null);
assert.equal(s.quote(offer,{...policy,paymentFeeBps:10000},now),null);
assert.equal(s.bestOffer([offer],policy,'phone','13-256-new',now),null);
assert.equal(s.bestOffer([offer,{...offer,supplierCostMinor:9000}],policy,'phone','13-128-new',now).priceMinor,10104);
assert.equal(s.validBarcode('4006381333931'),'4006381333931');
assert.equal(s.validBarcode('4006381333932'),null);
assert.equal(s.validBarcode('https://bad.example'),null);
assert.equal(s.validBarcode('036000291452'),'036000291452');
assert(s.barcodeMatches({barcodes:['0036000291452']},'036000291452'));
assert(s.score({id:'ginger',name:'Ginger Smash'},'khemere')>0);
assert(s.score({id:'itau',name:'Itau Papa 12.5 kg'},'12.5kg')>0);
assert(s.score({id:'sugar',name:'Sugar'},'sugr')>0);
assert.equal(s.score({id:'tea',name:'Tea bags'},'iphone'),0);
console.log('Search, barcode and pricing: 21 assertions passed.');
